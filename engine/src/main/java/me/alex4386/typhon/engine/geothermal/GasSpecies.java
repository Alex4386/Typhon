package me.alex4386.typhon.engine.geothermal;

/** Hazardous volcanic gases reported in {@link GasHazard} events. */
public enum GasSpecies {
    /** Carbon dioxide: odourless, denser than air, pools in depressions. */
    CO2,
    /** Sulfur dioxide: magmatic, acidic, dominant at high temperature. */
    SO2,
    /** Hydrogen sulfide: hydrothermal, dominant at low temperature. */
    H2S
}
